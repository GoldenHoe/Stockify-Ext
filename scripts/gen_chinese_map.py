def main() -> int:
    root = pathlib.Path(__file__).resolve().parent.parent
    sources = sorted((root / "app/src/main/java").rglob("*.kt"))
    used = set()
    for path in sources:
        for ch in path.read_text(encoding="utf-8"):
            if "\u4e00" <= ch <= "\u9fff":
                used.add(ch)

    # Characters that survive conversion must already be Simplified; anything else
    # has to be declared above. The list is printed for review because a few
    # Taiwan-only glyphs are shared with Simplified usage.
    uncovered = sorted(ch for ch in used if ch not in CHAR_MAP)
    print(f"{len(used)} distinct characters, {len(uncovered)} without a mapping")
    print("review for Traditional glyphs: " + "".join(uncovered))

    mapped_in_use = {src: dst for src, dst in CHAR_MAP.items() if src in used and src != dst}
    print(f"{len(mapped_in_use)} mapped characters are actually used")

    pairs = sorted(CHAR_MAP.items())
    trad = "".join(src for src, _ in pairs)
    simp = "".join(dst for _, dst in pairs)
    assert len(trad) == len(simp)
    assert len(set(trad)) == len(trad)

    lines = []
    lines.append('package com.rsps1008.stockify.ui.text')
    lines.append("")
    lines.append("/**")
    lines.append(" * Traditional/Simplified Chinese conversion used by [localized] and [Text].")
    lines.append(" *")
    lines.append(" * The app stores Traditional Chinese in Room column names and in CSV values, so")
    lines.append(" * conversion happens at render time only and never rewrites persisted data.")
    lines.append(" */")
    lines.append("internal object ChineseTextConverter {")
    lines.append(f'    private const val REVERSE_IDENTITY_CHARS = "{REVERSE_IDENTITY}"')
    lines.append("")
    lines.append("    private const val TRADITIONAL_CHARS =")
    for i in range(0, len(trad), 48):
        chunk = trad[i:i + 48]
        continuation = " +" if i + 48 < len(trad) else ""
        lines.append(f'        "{chunk}"{continuation}')
    lines.append("")
    lines.append("    private const val SIMPLIFIED_CHARS =")
    for i in range(0, len(simp), 48):
        chunk = simp[i:i + 48]
        continuation = " +" if i + 48 < len(simp) else ""
        lines.append(f'        "{chunk}"{continuation}')
    lines.append("")
    lines.append("    private val charMap: Map<Char, Char> by lazy {")
    lines.append("        val map = HashMap<Char, Char>(TRADITIONAL_CHARS.length * 2)")
    lines.append("        TRADITIONAL_CHARS.forEachIndexed { index, ch ->")
    lines.append("            map[ch] = SIMPLIFIED_CHARS[index]")
    lines.append("        }")
    lines.append("        map")
    lines.append("    }")
    lines.append("")
    lines.append("    private val phrases: List<Pair<String, String>> = listOf(")
    for src, dst in PHRASES:
        lines.append(f'        "{src}" to "{dst}",')
    lines.append("    )")
    lines.append("")
    lines.append("    private val cache = object : LinkedHashMap<String, String>(256, 0.75f, true) {")
    lines.append("        override fun removeEldestEntry(eldest: MutableMap.MutableEntry<String, String>?) =")
    lines.append("            size > 2048")
    lines.append("    }")
    lines.append("")
    lines.append("    fun convert(text: String): String {")
    lines.append("        if (text.isEmpty()) return text")
    lines.append("        synchronized(cache) { cache[text]?.let { return it } }")
    lines.append("        val converted = convertUncached(text)")
    lines.append("        synchronized(cache) { cache[text] = converted }")
    lines.append("        return converted")
    lines.append("    }")
    lines.append("")
    lines.append("    private fun convertUncached(text: String): String {")
    lines.append("        var result = text")
    lines.append("        for ((traditional, simplified) in phrases) {")
    lines.append("            if (result.contains(traditional)) {")
    lines.append("                result = result.replace(traditional, simplified)")
    lines.append("            }")
    lines.append("        }")
    lines.append("        var changed = false")
    lines.append("        val buffer = StringBuilder(result.length)")
    lines.append("        for (ch in result) {")
    lines.append("            val mapped = charMap[ch]")
    lines.append("            if (mapped == null) {")
    lines.append("                buffer.append(ch)")
    lines.append("            } else {")
    lines.append("                buffer.append(mapped)")
    lines.append("                changed = true")
    lines.append("            }")
    lines.append("        }")
    lines.append("        return if (changed) buffer.toString() else result")
    lines.append("    }")
    lines.append("")
    lines.append("    /** True when [text] contains at least one Traditional-only character. */")
    lines.append("    fun isTraditional(text: String): Boolean = text.any { charMap.containsKey(it) }")
    lines.append("")
    lines.append("    private val reverseCharMap: Map<Char, Char> by lazy {")
    lines.append("        val skip = REVERSE_IDENTITY_CHARS.toSet()")
    lines.append("        val map = HashMap<Char, Char>(TRADITIONAL_CHARS.length * 2)")
    lines.append("        TRADITIONAL_CHARS.forEachIndexed { index, ch ->")
    lines.append("            val simplified = SIMPLIFIED_CHARS[index]")
    lines.append("            if (simplified !in skip) map.putIfAbsent(simplified, ch)")
    lines.append("        }")
    lines.append("        map")
    lines.append("    }")
    lines.append("")
    lines.append("    private val reversePhrases: List<Pair<String, String>> =")
    lines.append("        phrases.sortedByDescending { it.second.length }.map { (traditional, simplified) ->")
    lines.append("            simplified to traditional")
    lines.append("        }")
    lines.append("")
    lines.append("    /**")
    lines.append("     * Best-effort Simplified -> Traditional conversion. Storage and searchable")
    lines.append("     * data stay Traditional, so a Simplified search term has to be mapped back")
    lines.append("     * before it can match. Ambiguous characters resolve to the first table entry.")
    lines.append("     */")
    lines.append("    fun toTraditional(text: String): String {")
    lines.append("        if (text.isEmpty()) return text")
    lines.append("        var result = text")
    lines.append("        for ((simplified, traditional) in reversePhrases) {")
    lines.append("            if (result.contains(simplified)) {")
    lines.append("                result = result.replace(simplified, traditional)")
    lines.append("            }")
    lines.append("        }")
    lines.append("        val buffer = StringBuilder(result.length)")
    lines.append("        for (ch in result) {")
    lines.append("            buffer.append(reverseCharMap[ch] ?: ch)")
    lines.append("        }")
    lines.append("        return buffer.toString()")
    lines.append("    }")
    lines.append("}")
    lines.append("")

    target = root / "app/src/main/java/com/rsps1008/stockify/ui/text/ChineseTextConverter.kt"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {target.relative_to(root)} ({len(pairs)} chars, {len(PHRASES)} phrases)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
